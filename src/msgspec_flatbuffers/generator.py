def _is_byte_vector(type_ref: TypeReference) -> bool:
    return (
        type_ref.base_type is BaseType.VECTOR
        and type_ref.element is BaseType.UBYTE
        and type_ref.index < 0
    )


@lru_cache(maxsize=4096)
def _snake_case(value: str) -> str:
    value = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", value)
    value = re.sub(r"[^0-9A-Za-z_]", "_", value).lower()
    if value and value[0].isdigit():
        value = f"_{value}"
    return value or "generated"


@lru_cache(maxsize=4096)
def _identifier(value: str) -> str:
    value = re.sub(r"\W", "_", value)
    if value and value[0].isdigit():
        value = f"_{value}"
    if keyword.iskeyword(value):
        value = f"{value}_"
    return value


@lru_cache(maxsize=4096)
def _short_name(qualified_name: str) -> str:
    return _identifier(qualified_name.rsplit(".", 1)[-1])


@lru_cache(maxsize=4096)
def _namespace(qualified_name: str) -> tuple[str, ...]:
    parts = qualified_name.split(".")
    return tuple(parts[:-1])


def _declaration_path(declaration_file: str | None) -> str:
    if declaration_file is None:
        raise GenerationError("flatc did not record a declaration file")
    return declaration_file.removeprefix("//")


def _definition_module(
    qualified_name: str,
    declaration_file: str | None,
    package_prefix: tuple[str, ...],
) -> str:
    namespace = tuple(_snake_case(part) for part in _namespace(qualified_name))
    module = _snake_case(Path(_declaration_path(declaration_file)).stem)
    return ".".join((*package_prefix, *namespace, module))


@lru_cache(maxsize=1024)
def _field_order(item: ObjectDefinition) -> tuple[FieldDefinition, ...]:
    fields = [field for field in item.fields if not field.deprecated]
    key = (lambda field: field.offset) if item.is_struct else (lambda field: field.id)
    return tuple(sorted(fields, key=key))


class _Context:
    def __init__(
        self,
        schema: Schema,
        declaration_file: str,
        package_prefix: tuple[str, ...],
    ) -> None:
        self.schema = schema
        self.declaration_file = declaration_file
        self.package_prefix = package_prefix
        self._nested_targets: dict[
            tuple[str, int], ObjectDefinition | None
        ] = {}
        self._union_arms: dict[str, tuple[_UnionArm, ...]] = {}
        self._union_pairs: dict[str, tuple[_UnionPair, ...]] = {}
        self._dynamic_pairs: dict[str, tuple[_DynamicPair, ...]] = {}

    def object_for(self, type_ref: TypeReference) -> ObjectDefinition:
        if type_ref.index < 0 or type_ref.index >= len(self.schema.objects):
            raise GenerationError(f"invalid object type index {type_ref.index}")
        return self.schema.objects[type_ref.index]

    def enum_for(self, type_ref: TypeReference) -> EnumDefinition | None:
        if type_ref.index < 0:
            return None
        if type_ref.index >= len(self.schema.enums):
            raise GenerationError(f"invalid enum type index {type_ref.index}")
        return self.schema.enums[type_ref.index]

    def nested_target(
        self,
        owner: ObjectDefinition,
        field: FieldDefinition,
    ) -> ObjectDefinition | None:
        cache_key = (owner.name, field.id)
        if cache_key in self._nested_targets:
            return self._nested_targets[cache_key]
        target_name = field.nested_flatbuffer
        if target_name is None:
            self._nested_targets[cache_key] = None
            return None
        if not _is_byte_vector(field.type):
            raise GenerationError(
                f"nested_flatbuffer field {owner.name}.{field.name} "
                "must be a [ubyte] vector"
            )
        if "." in target_name:
            candidates = (target_name,)
        else:
            namespace = ".".join(_namespace(owner.name))
            candidates = (
                f"{namespace}.{target_name}" if namespace else target_name,
            )
        matches = [item for item in self.schema.objects if item.name in candidates]
        if len(matches) != 1:
            raise GenerationError(
                f"nested_flatbuffer target {target_name!r} for "
                f"{owner.name}.{field.name} was not found"
            )
        target = matches[0]
        if target.is_struct:
            raise GenerationError(
                f"nested_flatbuffer target {target.name} must be a table"
            )
        self._nested_targets[cache_key] = target
        return target

    def union_enum(self, type_ref: TypeReference) -> EnumDefinition:
        enum = self.enum_for(type_ref)
        if enum is None or not enum.is_union:
            raise GenerationError("union field does not reference a union enum")
        return enum

    def union_arms(self, enum: EnumDefinition) -> tuple[_UnionArm, ...]:
        cached = self._union_arms.get(enum.name)
        if cached is not None:
            return cached
        if enum.underlying_type.base_type is not BaseType.UTYPE:
            raise GenerationError(
                f"union {enum.name} must use the UTYPE discriminator"
            )
        none_values = [
            value
            for value in enum.values
            if value.union_type is not None
            and value.union_type.base_type is BaseType.NONE
        ]
        if len(none_values) != 1:
            raise GenerationError(
                f"union {enum.name} must define exactly one NONE alternative"
            )
        if none_values[0].value != 0:
            raise GenerationError(
                f"union {enum.name} NONE alternative must have tag 0"
            )
        seen_objects: set[int] = set()
        seen_tags = {0}
        arms: list[_UnionArm] = []
        for value in enum.values:
            union_type = value.union_type
            if union_type is None:
                raise GenerationError(
                    f"union alternative {enum.name}.{value.name} has no type"
                )
            if union_type.base_type is BaseType.NONE:
                continue
            if value.value < 1 or value.value > 255:
                raise GenerationError(
                    f"union alternative {enum.name}.{value.name} tag "
                    f"{value.value} is outside uint8 range"
                )
            if value.value in seen_tags:
                raise GenerationError(
                    f"union {enum.name} has duplicate discriminator tag "
                    f"{value.value}"
                )
            seen_tags.add(value.value)
            if union_type.base_type is not BaseType.OBJECT:
                raise GenerationError(
                    f"unsupported union alternative {enum.name}.{value.name}: "
                    f"{union_type.base_type.name.lower()}"
                )
            target = self.object_for(union_type)
            if target.is_struct:
                raise GenerationError(
                    f"unsupported union struct alternative "
                    f"{enum.name}.{value.name}"
                )
            if union_type.index in seen_objects:
                raise GenerationError(
                    f"union aliases are not supported: {enum.name}"
                )
            seen_objects.add(union_type.index)
            arms.append(_UnionArm(value.value, value.name, target))
        if not arms:
            raise GenerationError(f"union {enum.name} has no table alternatives")
        result = tuple(arms)
        self._union_arms[enum.name] = result
        return result

    def union_pairs(self, item: ObjectDefinition) -> tuple[_UnionPair, ...]:
        cached = self._union_pairs.get(item.name)
        if cached is not None:
            return cached
        if item.is_struct and any(
            field.type.base_type is BaseType.UNION
            or field.type.base_type is BaseType.VECTOR
            and field.type.element is BaseType.UNION
            for field in item.fields
        ):
            raise GenerationError(f"FlatBuffers struct {item.name} cannot contain unions")
        fields = _field_order(item)
        by_id = {field.id: field for field in fields}
        if len(by_id) != len(fields):
            raise GenerationError(f"object {item.name} has duplicate field ids")
        pairs: list[_UnionPair] = []
        paired_type_field_ids: set[int] = set()
        for value_field in fields:
            type_ref = value_field.type
            scalar_union = type_ref.base_type is BaseType.UNION
            vector_union = (
                type_ref.base_type is BaseType.VECTOR
                and type_ref.element is BaseType.UNION
            )
            if not scalar_union and not vector_union:
                continue
            enum = self.union_enum(type_ref)
            type_field = by_id.get(value_field.id - 1)
            expected_name = f"{value_field.name}_type"
            if type_field is None or type_field.name != expected_name:
                raise GenerationError(
                    f"union field {item.name}.{value_field.name} has no matching "
                    f"{expected_name!r} discriminator"
                )
            type_type = type_field.type
            valid_type = (
                type_type.base_type is BaseType.UTYPE
                if scalar_union
                else type_type.base_type is BaseType.VECTOR
                and type_type.element is BaseType.UTYPE
            )
            if not valid_type or type_type.index != type_ref.index:
                raise GenerationError(
                    f"union field {item.name}.{value_field.name} has a malformed "
                    "discriminator pair"
                )
            paired_type_field_ids.add(type_field.id)
            pairs.append(
                _UnionPair(
                    value_field,
                    type_field,
                    enum,
                    self.union_arms(enum),
                    vector_union,
                )
            )
        for field in fields:
            can_be_discriminator = (
                field.type.base_type is BaseType.UTYPE
                or field.type.base_type is BaseType.VECTOR
                and field.type.element is BaseType.UTYPE
            )
            if not can_be_discriminator:
                continue
            enum = self.enum_for(field.type)
            is_union_type = enum is not None and enum.is_union
            if is_union_type and field.id not in paired_type_field_ids:
                raise GenerationError(
                    f"orphan union discriminator {item.name}.{field.name}"
                )
        result = tuple(pairs)
        self._union_pairs[item.name] = result
        return result

    def dynamic_pairs(self, item: ObjectDefinition) -> tuple[_DynamicPair, ...]:
        cached = self._dynamic_pairs.get(item.name)
        if cached is not None:
            return cached
        fields = _field_order(item)
        by_name = {field.name: field for field in fields}
        pairs: list[_DynamicPair] = []
        paired_type_field_ids: set[int] = set()
        for value_field in fields:
            type_field_name = value_field.dynamic_flatbuffer
            if type_field_name is None:
                continue
            payload_name = f"{item.name}.{value_field.name}"
            if item.is_struct:
                raise GenerationError(
                    f"FlatBuffers struct {item.name} cannot contain dynamic fields"
                )
            if not _is_byte_vector(value_field.type):
                raise GenerationError(
                    f"dynamic_flatbuffer field {payload_name} must be a "
                    "[ubyte] vector"
                )
            if value_field.nested_flatbuffer is not None:
                raise GenerationError(
                    f"field {payload_name} cannot use both "
                    "dynamic_flatbuffer and nested_flatbuffer"
                )
            allow_pattern = value_field.dynamic_allow
            if allow_pattern is None:
                raise GenerationError(
                    f"dynamic_flatbuffer field {payload_name} "
                    "requires dynamic_allow"
                )
            try:
                allowed_prefix = dynamic_allow_prefix(allow_pattern)
            except ValueError as error:
                raise GenerationError(
                    f"invalid dynamic_allow on {payload_name}: {error}"
                ) from error
            type_field = by_name.get(type_field_name)
            if type_field is None:
                raise GenerationError(
                    f"dynamic_flatbuffer field {payload_name} "
                    f"references missing type field {type_field_name!r}"
                )
            qualified_type_field_name = f"{item.name}.{type_field.name}"
            if (
                type_field.id == value_field.id
                or type_field.id in paired_type_field_ids
            ):
                raise GenerationError(
                    f"dynamic FlatBuffer type field {qualified_type_field_name} "
                    "must belong to exactly one payload"
                )
            if (
                type_field.type.base_type is not BaseType.STRING
                or type_field.required != value_field.required
            ):
                raise GenerationError(
                    f"dynamic FlatBuffer type field {qualified_type_field_name} "
                    "must be a string with matching requiredness"
                )
            paired_type_field_ids.add(type_field.id)
            pairs.append(_DynamicPair(value_field, type_field, allowed_prefix))
        for field in fields:
            if field.dynamic_allow is not None and field.dynamic_flatbuffer is None:
                raise GenerationError(
                    f"field {item.name}.{field.name} uses dynamic_allow without "
                    "dynamic_flatbuffer"
                )
        result = tuple(pairs)
        self._dynamic_pairs[item.name] = result
        return result

    def scalar_spec(self, base_type: BaseType) -> _ScalarSpec:
        try:
            return _SCALARS[base_type]
        except KeyError as error:
            raise GenerationError(f"unsupported scalar type {base_type.name}") from error

    def scalar_python_type(self, type_ref: TypeReference) -> str:
        enum = self.enum_for(type_ref)
        if enum is not None:
            return _short_name(enum.name)
        return self.scalar_spec(type_ref.base_type).python_type

    def model_type(self, type_ref: TypeReference) -> str:
        if type_ref.base_type in _SCALARS:
            return self.scalar_python_type(type_ref)
        if type_ref.base_type is BaseType.STRING:
            return "str"
        if type_ref.base_type is BaseType.OBJECT:
            return _short_name(self.object_for(type_ref).name)
        if type_ref.base_type is BaseType.VECTOR:
            return self.vector_model_type(type_ref)
        raise GenerationError(f"unsupported model type {type_ref.base_type.name}")

    def vector_model_type(self, type_ref: TypeReference) -> str:
        element = type_ref.element
        if _is_byte_vector(type_ref):
            return "bytes"
        if element in _SCALARS:
            enum = self.enum_for(type_ref)
            if enum is not None:
                return f"list[{_short_name(enum.name)}]"
            return f"npt.NDArray[{self.scalar_spec(element).numpy_type}]"
        if element is BaseType.STRING:
            return "list[str]"
        if element is BaseType.OBJECT:
            return f"list[{_short_name(self.object_for(type_ref).name)}]"
        raise GenerationError(f"unsupported vector element type {element.name}")

    def view_type(self, type_ref: TypeReference) -> str:
        if type_ref.base_type in _SCALARS:
            return self.scalar_python_type(type_ref)
        if type_ref.base_type is BaseType.STRING:
            return "str"
        if type_ref.base_type is BaseType.OBJECT:
            return f"{_short_name(self.object_for(type_ref).name)}View"
        if type_ref.base_type is BaseType.VECTOR:
            return self.vector_view_type(type_ref)
        raise GenerationError(f"unsupported view type {type_ref.base_type.name}")

    def vector_view_type(self, type_ref: TypeReference) -> str:
        element = type_ref.element
        if _is_byte_vector(type_ref):
            return "memoryview"
        if element in _SCALARS:
            dtype = self.scalar_spec(element).numpy_type
            return f"npt.NDArray[{dtype}]"
        if element is BaseType.STRING:
            return "StringVector"
        if element is BaseType.OBJECT:
            item = self.object_for(type_ref)
            wrapper = "StructVector" if item.is_struct else "TableVector"
            return f"{wrapper}[{_short_name(item.name)}View]"
        raise GenerationError(f"unsupported vector element type {element.name}")

    def default_expression(self, field: FieldDefinition) -> str:
        if field.optional:
            return "None"
        enum = self.enum_for(field.type)
        if enum is not None:
            return f"{_short_name(enum.name)}({field.default_integer})"
        if field.type.base_type is BaseType.BOOL:
            return repr(bool(field.default_integer))
        if field.type.base_type in (BaseType.FLOAT, BaseType.DOUBLE):
            return _float_literal(field.default_real)
        return repr(field.default_integer)

    def referenced_definitions(
        self,
        local_objects: list[ObjectDefinition],
        local_enums: list[EnumDefinition],
    ) -> tuple[dict[str, set[str]], dict[str, set[str]]]:
        objects: dict[str, set[str]] = defaultdict(set)
        enums: dict[str, set[str]] = defaultdict(set)
        for item in local_objects:
            self.dynamic_pairs(item)
            for field in item.fields:
                nested = self.nested_target(item, field)
                if nested is not None:
                    self._record_nested_object(objects, nested)
                type_ref = field.type
                if type_ref.base_type is BaseType.OBJECT:
                    self._record_object(objects, self.object_for(type_ref))
                elif type_ref.base_type is BaseType.VECTOR:
                    if type_ref.element is BaseType.OBJECT:
                        self._record_object(objects, self.object_for(type_ref))
                    elif type_ref.element in _SCALARS:
                        enum = self.enum_for(type_ref)
                        if enum is not None:
                            self._record_enum(enums, enum)
                elif type_ref.base_type in _SCALARS:
                    enum = self.enum_for(type_ref)
                    if enum is not None:
                        self._record_enum(enums, enum)
            for pair in self.union_pairs(item):
                self._record_enum(enums, pair.enum)
                for arm in pair.arms:
                    self._record_object(objects, arm.object)
        for enum in local_enums:
            if enum.is_union:
                for arm in self.union_arms(enum):
                    self._record_object(objects, arm.object)
        return objects, enums

    def _record_nested_object(
        self,
        imports: dict[str, set[str]],
        item: ObjectDefinition,
    ) -> None:
        if item.declaration_file == self.declaration_file:
            return
        module = _definition_module(
            item.name,
            item.declaration_file,
            self.package_prefix,
        )
        name = _short_name(item.name)
        imports[module].update((name, f"{name}View"))

    def _record_object(
        self,
        imports: dict[str, set[str]],
        item: ObjectDefinition,
    ) -> None:
        if item.declaration_file == self.declaration_file:
            return
        module = _definition_module(
            item.name,
            item.declaration_file,
            self.package_prefix,
        )
        name = _short_name(item.name)
        imports[module].update((name, f"{name}View"))

    def _record_enum(
        self,
        imports: dict[str, set[str]],
        item: EnumDefinition,
    ) -> None:
        if item.declaration_file == self.declaration_file:
            return
        module = _definition_module(
            item.name,
            item.declaration_file,
            self.package_prefix,
        )
        imports[module].add(_short_name(item.name))
        if item.is_union:
            imports[module].add(f"_FB_UNION_{_short_name(item.name)}")


def _float_literal(value: float) -> str:
    if value != value:
        return 'float("nan")'
    if value == float("inf"):
        return 'float("inf")'
    if value == float("-inf"):
        return 'float("-inf")'
    return repr(value)


def _documentation(lines: tuple[str, ...], indent: str = "    ") -> list[str]:
    if not lines:
        return []
    text = "\n".join(lines)
    return [f"{indent}{text!r}"]


def _has_marker_attribute(item: ObjectDefinition, key: str) -> bool:
    matches = [attribute for attribute in item.attributes if attribute.key == key]
    if len(matches) > 1:
        raise GenerationError(f"table {item.name} has duplicate {key!r} attributes")
    if not matches:
        return False
    if matches[0].value not in (None, "0"):
        raise GenerationError(f"table {item.name} attribute {key!r} takes no value")
    return True


def _union_model_type(pair: _UnionPair) -> str:
    return " | ".join(_short_name(arm.object.name) for arm in pair.arms)


def _union_view_type(pair: _UnionPair) -> str:
    return " | ".join(f"{_short_name(arm.object.name)}View" for arm in pair.arms)


def _dynamic_value_type_name(
    owner: ObjectDefinition,
    pair: _DynamicPair,
) -> str:
    return (
        f"_Dynamic_{_short_name(owner.name)}_"
        f"{_identifier(pair.value_field.name)}"
    )


def _render_dynamic_value_type(
    owner: ObjectDefinition,
    pair: _DynamicPair,
) -> list[str]:
    return [
        f"class {_dynamic_value_type_name(owner, pair)}(DynamicValue):",
        "    __slots__ = ()",
        f"    _allowed_prefix = {pair.allowed_prefix!r}",
    ]


def _model_field_line(
    context: _Context,
    owner: ObjectDefinition,
    field: FieldDefinition,
    union_pair: _UnionPair | None,
    dynamic_pair: _DynamicPair | None,
) -> str:
    name = _identifier(field.name)
    nested = context.nested_target(owner, field)
    if dynamic_pair is not None:
        annotation = _dynamic_value_type_name(owner, dynamic_pair)
    elif union_pair is not None:
        annotation = (
            f"list[{_union_model_type(union_pair)}]"
            if union_pair.vector
            else _union_model_type(union_pair)
        )
    elif nested is not None:
        annotation = _short_name(nested.name)
    else:
        annotation = context.model_type(field.type)
    if owner.is_struct:
        return f"    {name}: {annotation}"
    if field.type.base_type in _SCALARS:
        if field.optional:
            return f"    {name}: {annotation} | None = None"
        return f"    {name}: {annotation} = {context.default_expression(field)}"
    if field.required:
        return f"    {name}: {annotation}"
    return f"    {name}: {annotation} | None = None"


def _render_enum(context: _Context, item: EnumDefinition) -> list[str]:
    if item.is_union:
        context.union_arms(item)
    name = _short_name(item.name)
    lines = [f"class {name}(OpenIntEnum):"]
    lines.extend(_documentation(item.documentation))
    if not item.values:
        lines.append("    pass")
    else:
        for value in item.values:
            lines.append(f"    {_identifier(value.name)} = {value.value}")
    return lines


def _is_numeric_model_vector(context: _Context, field: FieldDefinition) -> bool:
    type_ref = field.type
    return (
        type_ref.base_type is BaseType.VECTOR
        and type_ref.element in _SCALARS
        and not _is_byte_vector(type_ref)
        and context.enum_for(type_ref) is None
    )


def _render_model_equality(
    context: _Context,
    item: ObjectDefinition,
    fields: Sequence[FieldDefinition],
) -> list[str]:
    name = _short_name(item.name)
    lines = [
        "    def __eq__(self, other: object) -> bool:",
        f"        if type(other) is not {name}:",
        "            return False",
        "        return (",
    ]
    comparisons: list[str] = []
    for field in fields:
        property_name = _identifier(field.name)
        if _is_numeric_model_vector(context, field):
            arrays_equal = (
                f"self.{property_name}.dtype == other.{property_name}.dtype and "
                f"np.array_equal(self.{property_name}, other.{property_name})"
            )
            comparison = (
                arrays_equal
                if field.required
                else (
                    f"(self.{property_name} is None and "
                    f"other.{property_name} is None) or "
                    f"(self.{property_name} is not None and "
                    f"other.{property_name} is not None and {arrays_equal})"
                )
            )
        else:
            comparison = f"self.{property_name} == other.{property_name}"
        comparisons.append(comparison)
    lines.append(f"            ({comparisons[0]})")
    lines.extend(f"            and ({comparison})" for comparison in comparisons[1:])
    lines.extend(
        [
            "        )",
            "",
            "    def __ne__(self, other: object) -> bool:",
            "        return not self == other",
        ]
    )
    return lines


def _render_union_dispatch(context: _Context, item: EnumDefinition) -> list[str]:
    arms = context.union_arms(item)
    none_value = next(
        value
        for value in item.values
        if value.union_type is not None
        and value.union_type.base_type is BaseType.NONE
    )
    lines = [
        f"_FB_UNION_{_short_name(item.name)} = UnionDispatch(",
        f"    {item.name!r},",
        f"    {none_value.value},",
        "    {",
    ]
    for arm in arms:
        lines.append(
            f"        {arm.tag}: {_short_name(arm.object.name)}View,"
        )
    lines.extend(("    },", ")"))
    return lines


def _render_model(
    context: _Context,
    item: ObjectDefinition,
    root: bool,
) -> list[str]:
    name = _short_name(item.name)
    fields = _field_order(item)
    union_pairs = context.union_pairs(item)
    union_pairs_by_value_id = {
        pair.value_field.id: pair for pair in union_pairs
    }
    dynamic_pairs = context.dynamic_pairs(item)
    dynamic_pairs_by_value_id = {
        pair.value_field.id: pair for pair in dynamic_pairs
    }
    hidden_type_field_ids = _hidden_type_field_ids(union_pairs, dynamic_pairs)
    model_fields = [
        field for field in fields if field.id not in hidden_type_field_ids
    ]
    has_numeric_vectors = any(
        _is_numeric_model_vector(context, field) for field in model_fields
    )
    options = ["frozen=True", "kw_only=True"]
    if not item.is_struct:
        reserved_fields = {
            _MSGSPEC_TAG_FIELD,
            _OPAQUE_DATA_FIELD,
        }
        conflict = next(
            (
                _identifier(field.name)
                for field in fields
                if _identifier(field.name) in reserved_fields
            ),
            None,
        )
        if conflict is not None:
            description = (
                "msgspec tag field"
                if conflict == _MSGSPEC_TAG_FIELD
                else "dynamic payload field"
            )
            raise GenerationError(
                f"table {item.name} uses reserved {description} {conflict!r}"
            )
        options.extend(
            (
                f"tag={item.name!r}",
                f"tag_field={_MSGSPEC_TAG_FIELD!r}",
            )
        )
    if has_numeric_vectors:
        options.append("eq=False")
    lines = [f"class {name}(msgspec.Struct, {', '.join(options)}):"]
    lines.extend(_documentation(item.documentation))
    if not model_fields:
        lines.append("    pass")
    for field in model_fields:
        lines.append(
            _model_field_line(
                context,
                item,
                field,
                union_pairs_by_value_id.get(field.id),
                dynamic_pairs_by_value_id.get(field.id),
            )
        )
    if has_numeric_vectors:
        lines.append("")
        lines.extend(_render_model_equality(context, item, model_fields))
    if not item.is_struct:
        if model_fields or has_numeric_vectors:
            lines.append("")
        identifier = (
            repr(context.schema.file_identifier)
            if root and context.schema.file_identifier is not None
            else "None"
        )
        lines.extend(
            [
                "    def to_flatbuffer(",
                "        self,",
                "        *,",
                "        size_prefixed: bool = False,",
                "        initial_size: int = 0,",
                "    ) -> memoryview:",
                "        return _FB_NATIVE_MODULE.pack(",
                f"            {item.name!r},",
                "            self,",
                f"            identifier={identifier},",
                "            size_prefixed=size_prefixed,",
                "            initial_size=initial_size,",
                "        )",
            ]
        )
    return lines


