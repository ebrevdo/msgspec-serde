def _scalar_load_lines(
    context: _Context,
    field: FieldDefinition,
    *,
    struct: bool,
    target: str,
    indent: str,
    use_table_locals: bool = False,
) -> list[str]:
    """Render one checked scalar load without generic runtime dispatch."""

    scalar = context.scalar_spec(field.type.base_type)
    reader, _ = _SCALAR_READERS[field.type.base_type]
    enum = context.enum_for(field.type)
    present = f"{reader}.unpack_from({{buffer}}, {{position}})[0]"
    if enum is not None:
        present = f"{_short_name(enum.name)}({present})"

    if struct:
        return [
            f"{indent}{target} = "
            + present.format(
                buffer="self._buffer",
                position=f"self._struct_offset + {field.offset}",
            )
        ]

    if field.offset < 4 or field.offset % 2:
        raise GenerationError(
            f"invalid vtable offset {field.offset} for scalar field {field.name!r}"
        )

    default = context.default_expression(field)
    buffer = "_fb_buffer" if use_table_locals else "self._buffer"
    vtable_size = "_fb_vtable_size" if use_table_locals else "self._vtable_size"
    vtable_offset = (
        "_fb_vtable_offset" if use_table_locals else "self._vtable_offset"
    )
    object_size = "_fb_object_size" if use_table_locals else "self._object_size"
    table_offset = "_fb_table_offset" if use_table_locals else "self._table_offset"
    relative = f"{target}_relative"
    return [
        f"{indent}if {field.offset} >= {vtable_size}:",
        f"{indent}    {target} = {default}",
        f"{indent}else:",
        f"{indent}    {relative} = _UINT16.unpack_from("
        f"{buffer}, {vtable_offset} + {field.offset})[0]",
        f"{indent}    if {relative} == 0:",
        f"{indent}        {target} = {default}",
        f"{indent}    elif {relative} < 4 or "
        f"{relative} > {object_size} - {scalar.size}:",
        f"{indent}        raise InvalidBufferError("
        '"field lies outside its FlatBuffers table")',
        f"{indent}    else:",
        f"{indent}        {target} = "
        + present.format(
            buffer=buffer,
            position=f"{table_offset} + {relative}",
        ),
    ]


def _cache_slot(field: FieldDefinition) -> str:
    return f"_fb_cached_{_identifier(field.name)}"


def _struct_unpacker(
    context: _Context,
    item: ObjectDefinition,
) -> tuple[str, str] | None:
    """Return a composite unpacker name/format for a scalar-only struct."""

    if not item.is_struct:
        return None
    fields = _field_order(item)
    if not fields or any(field.type.base_type not in _SCALARS for field in fields):
        return None

    parts = ["<"]
    cursor = 0
    for field in fields:
        scalar = context.scalar_spec(field.type.base_type)
        if field.offset < cursor:
            raise GenerationError(f"overlapping struct field {field.name!r}")
        padding = field.offset - cursor
        if padding:
            parts.append("x" if padding == 1 else f"{padding}x")
        _, scalar_format = _SCALAR_READERS[field.type.base_type]
        parts.append(scalar_format.removeprefix("<"))
        cursor = field.offset + scalar.size
    if item.byte_size < cursor:
        raise GenerationError(f"struct {item.name!r} fields exceed its byte size")
    return f"_FB_UNPACK_{_short_name(item.name)}", "".join(parts)


def _complex_view_loader(context: _Context, field: FieldDefinition) -> str:
    type_ref = field.type
    if type_ref.base_type is BaseType.STRING:
        return f"self._read_string({field.offset})"
    if type_ref.base_type is BaseType.OBJECT:
        item = context.object_for(type_ref)
        method = "_read_struct" if item.is_struct else "_read_table"
        return f"self.{method}({field.offset}, {_short_name(item.name)}View)"
    if type_ref.base_type is BaseType.VECTOR:
        element = type_ref.element
        if _is_byte_vector(type_ref):
            return f"self._read_byte_vector({field.offset})"
        if element in _SCALARS:
            dtype = _NUMPY_DTYPES[element]
            return f"self._read_numpy_vector({field.offset}, {dtype!r})"
        if element is BaseType.STRING:
            return f"self._read_string_vector({field.offset})"
        if element is BaseType.OBJECT:
            item = context.object_for(type_ref)
            method = "_read_struct_vector" if item.is_struct else "_read_table_vector"
            return f"self.{method}({field.offset}, {_short_name(item.name)}View)"
        raise GenerationError(f"unsupported vector element type {element.name}")
    raise GenerationError(f"unsupported field type {type_ref.base_type.name}")


def _complex_cache_load_lines(
    context: _Context,
    field: FieldDefinition,
    *,
    target: str,
    indent: str,
) -> list[str]:
    """Render a direct per-field slot cache lookup and cold-path load."""

    slot = _cache_slot(field)
    lines = [
        f"{indent}try:",
        f"{indent}    {target} = self.{slot}",
        f"{indent}except AttributeError:",
        f"{indent}    {target} = {_complex_view_loader(context, field)}",
    ]
    if field.required:
        lines.extend(
            [
                f"{indent}    if {target} is None:",
                f"{indent}        raise InvalidBufferError("
                f"\"required field {field.name!r} is absent\")",
            ]
        )
    lines.append(f"{indent}    self.{slot} = {target}")
    return lines


def _complex_view_property(context: _Context, field: FieldDefinition) -> list[str]:
    name = _identifier(field.name)
    annotation = context.view_type(field.type)
    return_type = annotation if field.required else f"{annotation} | None"
    lines = [
        "    @property",
        f"    def {name}(self) -> {return_type}:",
        *_complex_cache_load_lines(
            context,
            field,
            target="value",
            indent="        ",
        ),
        "        return value",
    ]
    return lines


def _byte_vector_as_method(field: FieldDefinition) -> list[str]:
    property_name = _identifier(field.name)
    return_type = "_NestedViewT" if field.required else "_NestedViewT | None"
    cache_key = f"_fb_nested_views:{property_name}"
    lines = [
        f"    def {property_name}_as(",
        "        self,",
        "        view_type: type[_NestedViewT],",
        "        *,",
        "        size_prefixed: bool = False,",
        f"    ) -> {return_type}:",
        f"        payload = self.{property_name}",
    ]
    if not field.required:
        lines.extend(
            [
                "        if payload is None:",
                "            return None",
            ]
        )
    lines.extend(
        [
            "        try:",
            "            cache: dict[tuple[type[TableView], bool], Any] = (",
            f"                self._cache[{cache_key!r}]",
            "            )",
            "        except KeyError:",
            "            cache = {}",
            f"            self._cache[{cache_key!r}] = cache",
            "        key = (view_type, size_prefixed)",
            "        try:",
            "            return cache[key]",
            "        except KeyError:",
            "            value = view_type.from_buffer(",
            "                payload,",
            "                size_prefixed=size_prefixed,",
            "            )",
            "            cache[key] = value",
            "            return value",
        ]
    )
    return lines


