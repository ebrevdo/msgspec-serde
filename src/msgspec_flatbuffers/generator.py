def _model_conversion_expression(
    context: _Context,
    field: FieldDefinition,
    local: str,
) -> str:
    type_ref = field.type
    if type_ref.base_type is BaseType.STRING:
        expression = local
    elif type_ref.base_type is BaseType.OBJECT:
        expression = f"{local}.to_model()"
    elif type_ref.base_type is BaseType.VECTOR:
        element = type_ref.element
        if _is_byte_vector(type_ref):
            expression = f"bytes({local})"
        elif element in _SCALARS:
            enum = context.enum_for(type_ref)
            if enum is None:
                expression = (
                    f"np.array({local}, dtype="
                    f"{context.scalar_spec(element).numpy_type}, copy=True)"
                )
            else:
                enum_name = _short_name(enum.name)
                expression = f"list(map({enum_name}, {local}.tolist()))"
        elif element is BaseType.STRING:
            expression = f"list({local})"
        elif element is BaseType.OBJECT:
            item_name = _short_name(context.object_for(type_ref).name)
            expression = f"list(map({item_name}View.to_model, {local}))"
        else:
            raise GenerationError(f"unsupported vector element type {element.name}")
    else:
        raise GenerationError(f"unsupported complex type {type_ref.base_type.name}")

    if field.required:
        return expression
    return f"None if {local} is None else {expression}"


def _render_view(context: _Context, item: ObjectDefinition, root: bool) -> list[str]:
    name = _short_name(item.name)
    base = "StructView" if item.is_struct else "TableView"
    fields = _field_order(item)
    union_pairs = context.union_pairs(item)
    union_pairs_by_value_id = {
        pair.value_field.id: pair for pair in union_pairs
    }
    dynamic_pairs = context.dynamic_pairs(item)
    dynamic_pairs_by_value_id = {
        pair.value_field.id: pair for pair in dynamic_pairs
    }
    hidden_type_field_ids = _hidden_type_field_ids(union_pairs, dynamic_pairs)
    nested_targets = {
        field.id: target
        for field in fields
        if (target := context.nested_target(item, field)) is not None
    }
    cached_fields = [
        field for field in fields if field.type.base_type not in _SCALARS
    ]
    byte_vector_fields = [
        field
        for field in fields
        if _is_byte_vector(field.type)
        and field.id not in nested_targets
        and field.id not in dynamic_pairs_by_value_id
    ]
    property_names = {_identifier(field.name) for field in fields}
    for field in byte_vector_fields:
        method_name = f"{_identifier(field.name)}_as"
        if method_name in property_names:
            raise GenerationError(
                f"generated byte-vector helper {method_name!r} conflicts with a field"
            )
    for field in fields:
        if field.id in nested_targets:
            method_name = f"{_identifier(field.name)}_view"
            if method_name in property_names:
                raise GenerationError(
                    f"generated nested helper {method_name!r} conflicts with a field"
                )
        pair = union_pairs_by_value_id.get(field.id)
        if pair is not None and not pair.vector:
            method_name = f"{_identifier(field.name)}_view"
            if method_name in property_names:
                raise GenerationError(
                    f"generated union helper {method_name!r} conflicts with a field"
                )
        dynamic_pair = dynamic_pairs_by_value_id.get(field.id)
        if dynamic_pair is not None:
            method_name = f"{_identifier(field.name)}_dynamic"
            if method_name in property_names:
                raise GenerationError(
                    f"generated dynamic helper {method_name!r} conflicts with a field"
                )
    cache_slots = tuple(
        [*(_cache_slot(field) for field in cached_fields)]
        + [
            _nested_cache_slot(field)
            for field in fields
            if field.id in nested_targets
        ]
        + [
            _dynamic_cache_slot(pair.value_field)
            for pair in dynamic_pairs
        ]
    )
    lines = [f"class {name}View({base}):"]
    lines.extend(_documentation(item.documentation))
    lines.append(f"    __slots__ = {cache_slots!r}")
    if item.is_struct:
        lines.append(f"    __flatbuffer_size__ = {item.byte_size}")
    elif root and context.schema.file_identifier is not None:
        lines.append(
            f"    __flatbuffer_identifier__ = {context.schema.file_identifier.encode()!r}"
        )

    for field in fields:
        lines.append("")
        pair = union_pairs_by_value_id.get(field.id)
        if pair is not None:
            if pair.vector:
                lines.extend(_union_vector_property(pair))
            else:
                lines.extend(_union_view_method(pair))
        elif field.type.base_type in _SCALARS:
            lines.extend(_scalar_view_property(context, field, item.is_struct))
        elif item.is_struct:
            if field.type.base_type is not BaseType.OBJECT:
                raise GenerationError(
                    f"unsupported struct field type {field.type.base_type.name}"
                )
            nested = context.object_for(field.type)
            if not nested.is_struct:
                raise GenerationError("FlatBuffers structs may only contain structs")
            property_name = _identifier(field.name)
            nested_name = _short_name(nested.name)
            lines.extend(
                [
                    "    @property",
                    f"    def {property_name}(self) -> {nested_name}View:",
                    *_complex_cache_load_lines(
                        context,
                        field,
                        target="value",
                        indent="        ",
                    ),
                    "        return value",
                ]
            )
        else:
            lines.extend(_complex_view_property(context, field))

    for field in byte_vector_fields:
        lines.append("")
        lines.extend(_byte_vector_as_method(field))

    for field in fields:
        target = nested_targets.get(field.id)
        if target is not None:
            lines.append("")
            lines.extend(_nested_view_method(field, target))

    for pair in dynamic_pairs:
        lines.append("")
        lines.extend(_dynamic_view_method(item, pair))

    if fields:
        lines.append("")
    lines.append(f"    def to_model(self) -> {name}:")
    model_fields = [
        field for field in fields if field.id not in hidden_type_field_ids
    ]
    scalar_fields = [
        field for field in model_fields if field.type.base_type in _SCALARS
    ]
    unpacker = _struct_unpacker(context, item)
    if unpacker is not None:
        unpacker_name, _ = unpacker
        targets = ", ".join(
            f"_{_identifier(field.name)}" for field in scalar_fields
        )
        if len(scalar_fields) == 1:
            targets += ","
        lines.append(
            f"        {targets} = {unpacker_name}.unpack_from("
            "self._buffer, self._struct_offset)"
        )
        for field in scalar_fields:
            enum = context.enum_for(field.type)
            if enum is not None:
                local = f"_{_identifier(field.name)}"
                lines.append(f"        {local} = {_short_name(enum.name)}({local})")
    use_table_locals = not item.is_struct and len(scalar_fields) > 1
    if use_table_locals:
        lines.extend(
            [
                "        _fb_buffer = self._buffer",
                "        _fb_vtable_size = self._vtable_size",
                "        _fb_vtable_offset = self._vtable_offset",
                "        _fb_object_size = self._object_size",
                "        _fb_table_offset = self._table_offset",
            ]
        )
    for field in model_fields:
        property_name = _identifier(field.name)
        local = f"_{property_name}"
        pair = union_pairs_by_value_id.get(field.id)
        dynamic_pair = dynamic_pairs_by_value_id.get(field.id)
        if dynamic_pair is not None:
            lines.append(f"        {local} = self.{property_name}_dynamic()")
        elif pair is not None:
            if pair.vector:
                lines.extend(
                    _union_vector_cache_load_lines(
                        pair,
                        target=local,
                        indent="        ",
                    )
                )
            else:
                lines.extend(
                    _union_cache_load_lines(
                        pair,
                        target=local,
                        indent="        ",
                    )
                )
        elif field.id in nested_targets:
            lines.append(f"        {local} = self.{property_name}_view()")
        elif field.type.base_type in _SCALARS:
            if unpacker is not None:
                continue
            lines.extend(
                _scalar_load_lines(
                    context,
                    field,
                    struct=item.is_struct,
                    target=local,
                    indent="        ",
                    use_table_locals=use_table_locals,
                )
            )
        else:
            lines.extend(
                _complex_cache_load_lines(
                    context,
                    field,
                    target=local,
                    indent="        ",
                )
            )
    lines.append(f"        return {name}(")
    for field in model_fields:
        property_name = _identifier(field.name)
        pair = union_pairs_by_value_id.get(field.id)
        dynamic_pair = dynamic_pairs_by_value_id.get(field.id)
        if dynamic_pair is not None:
            expression = f"_{property_name}.to_model()"
            if not field.required:
                expression = (
                    f"None if _{property_name} is None else {expression}"
                )
        elif pair is not None:
            if pair.vector:
                expression = (
                    f"[item.to_model() for item in _{property_name}]"
                )
            else:
                expression = f"_{property_name}.to_model()"
            if not field.required:
                expression = (
                    f"None if _{property_name} is None else {expression}"
                )
        elif field.id in nested_targets:
            expression = f"_{property_name}.to_model()"
            if not field.required:
                expression = (
                    f"None if _{property_name} is None else {expression}"
                )
        elif field.type.base_type in _SCALARS:
            expression = f"_{property_name}"
        elif item.is_struct:
            expression = f"_{property_name}.to_model()"
        else:
            expression = _model_conversion_expression(
                context,
                field,
                f"_{property_name}",
            )
        lines.append(f"            {property_name}={expression},")
    lines.append("        )")
    return lines


def _native_plan_default(
    context: _Context,
    field: FieldDefinition,
) -> bool | int | float | None:
    if field.optional:
        return None
    if field.type.base_type is BaseType.BOOL:
        return bool(field.default_integer)
    if field.type.base_type in (BaseType.FLOAT, BaseType.DOUBLE):
        return field.default_real
    if field.type.base_type in _SCALARS:
        return field.default_integer
    return None


def _native_field_plan(
    context: _Context,
    owner: ObjectDefinition,
    field: FieldDefinition,
    union_pair: _UnionPair | None,
    dynamic_pair: _DynamicPair | None,
) -> dict[str, object]:
    type_ref = field.type
    plan: dict[str, object] = {
        "name": _identifier(field.name),
        "slot": field.id,
        "offset": field.offset,
        "optional": field.optional,
        "required": field.required,
        "default": _native_plan_default(context, field),
    }
    if union_pair is not None:
        plan.update(
            kind="union_vector" if union_pair.vector else "union",
            type_slot=union_pair.type_field.id,
            type_scalar=context.scalar_spec(
                union_pair.enum.underlying_type.base_type
            ).runtime_name,
            arms=[
                {"tag": arm.tag, "target": arm.object.name}
                for arm in union_pair.arms
            ],
        )
        return plan
    if dynamic_pair is not None:
        plan.update(
            kind="dynamic",
            type_slot=dynamic_pair.type_field.id,
            allowed_prefix=dynamic_pair.allowed_prefix,
        )
        return plan
    nested = context.nested_target(owner, field)
    if nested is not None:
        plan.update(kind="nested", target=nested.name)
        return plan
    if type_ref.base_type in _SCALARS:
        plan.update(
            kind="scalar",
            scalar=context.scalar_spec(type_ref.base_type).runtime_name,
        )
    elif type_ref.base_type is BaseType.STRING:
        plan["kind"] = "string"
    elif type_ref.base_type is BaseType.OBJECT:
        target = context.object_for(type_ref)
        plan.update(
            kind="struct" if target.is_struct else "table",
            target=target.name,
        )
    elif type_ref.base_type is BaseType.VECTOR:
        if _is_byte_vector(type_ref):
            plan["kind"] = "vector_byte"
        elif type_ref.element in _SCALARS:
            plan.update(
                kind="vector_scalar",
                scalar=context.scalar_spec(type_ref.element).runtime_name,
            )
        elif type_ref.element is BaseType.STRING:
            plan["kind"] = "vector_string"
        elif type_ref.element is BaseType.OBJECT:
            target = context.object_for(type_ref)
            plan.update(
                kind="vector_struct" if target.is_struct else "vector_table",
                target=target.name,
            )
        else:  # pragma: no cover - rejected by earlier generation checks
            raise GenerationError(
                f"unsupported native vector element {type_ref.element.name}"
            )
    else:  # pragma: no cover - rejected by earlier generation checks
        raise GenerationError(f"unsupported native field type {type_ref.base_type.name}")
    return plan


def _native_module_plan_bytes(context: _Context) -> bytes:
    objects: list[dict[str, object]] = []
    for item in context.schema.objects:
        union_pairs = context.union_pairs(item)
        dynamic_pairs = context.dynamic_pairs(item)
        union_by_value = {pair.value_field.id: pair for pair in union_pairs}
        dynamic_by_value = {pair.value_field.id: pair for pair in dynamic_pairs}
        hidden_type_field_ids = _hidden_type_field_ids(
            union_pairs,
            dynamic_pairs,
        )
        fields = [
            _native_field_plan(
                context,
                item,
                field,
                union_by_value.get(field.id),
                dynamic_by_value.get(field.id),
            )
            for field in _field_order(item)
            if field.id not in hidden_type_field_ids
        ]
        objects.append(
            {
                "name": item.name,
                "is_struct": item.is_struct,
                "byte_size": item.byte_size,
                "min_alignment": item.min_alignment,
                "fields": fields,
            }
        )
    return msgspec.msgpack.encode({"version": 1, "objects": objects})


def _render_root_builder(context: _Context, root: ObjectDefinition) -> list[str]:
    name = _short_name(root.name)
    function_name = f"build_{_snake_case(name)}"
    identifier = (
        repr(context.schema.file_identifier)
        if context.schema.file_identifier is not None
        else "None"
    )
    return [
        f"def {function_name}(",
        f"    value: {name},",
        "    *,",
        "    size_prefixed: bool = False,",
        "    initial_size: int = 0,",
        ") -> memoryview:",
        "    return _FB_NATIVE_MODULE.pack(",
        f"        {root.name!r},",
        "        value,",
        f"        identifier={identifier},",
        "        size_prefixed=size_prefixed,",
        "        initial_size=initial_size,",
        "    )",
    ]


def render_module(
    schema: Schema,
    declaration_file: str,
    *,
    package_prefix: Iterable[str] = (),
) -> str:
    """Render one deterministic Python module for one declaring ``.fbs`` file."""

    prefix = tuple(_snake_case(part) for part in package_prefix)
    context = _Context(schema, declaration_file, prefix)
    local_objects = [
        item for item in schema.objects if item.declaration_file == declaration_file
    ]
    local_enums = [
        item for item in schema.enums if item.declaration_file == declaration_file
    ]
    if not local_objects and not local_enums:
        raise GenerationError(f"no definitions declared in {declaration_file!r}")
    dynamic_field_pairs = [
        (item, pair)
        for item in local_objects
        for pair in context.dynamic_pairs(item)
    ]
    dynamic_value_field_ids = {
        (item.name, pair.value_field.id)
        for item, pair in dynamic_field_pairs
    }
    has_dynamic = bool(dynamic_field_pairs)
    has_byte_vector_helpers = any(
        _is_byte_vector(field.type)
        and context.nested_target(item, field) is None
        and (item.name, field.id) not in dynamic_value_field_ids
        for item in local_objects
        for field in item.fields
    )
    has_unions = any(item.is_union for item in local_enums) or any(
        context.union_pairs(item) for item in local_objects
    )
    typing_imports: list[str] = []
    if has_byte_vector_helpers:
        typing_imports.extend(("Any", "TypeVar"))
    if has_unions:
        typing_imports.append("cast")

    namespaces = {
        _namespace(item.name) for item in [*local_objects, *local_enums]
    }
    if len(namespaces) > 1:
        raise GenerationError(
            "one .fbs file declaring multiple namespaces is not supported yet"
        )

    root = None
    if schema.root_table is not None:
        candidate = schema.object(schema.root_table)
        if candidate.declaration_file == declaration_file:
            root = candidate
    dynamic_extension = False
    for item in local_objects:
        if not _has_marker_attribute(item, "dynamic_extension"):
            continue
        if item.is_struct or item is not root:
            raise GenerationError(
                f"dynamic extension {item.name} must be this file's root table"
            )
        dynamic_extension = True

    object_imports, enum_imports = context.referenced_definitions(
        local_objects,
        local_enums,
    )
    imported_origins: dict[str, set[str]] = defaultdict(set)
    for module in set(object_imports) | set(enum_imports):
        for imported_name in (
            object_imports.get(module, set()) | enum_imports.get(module, set())
        ):
            imported_origins[imported_name].add(module)
    local_symbols = {
        symbol
        for item in local_objects
        for name in (_short_name(item.name),)
        for symbol in (
            name,
            f"{name}View",
        )
    }
    for item in local_enums:
        enum_name = _short_name(item.name)
        local_symbols.add(enum_name)
        if item.is_union:
            local_symbols.add(f"_FB_UNION_{enum_name}")
    local_symbols.update(
        _dynamic_value_type_name(item, pair)
        for item, pair in dynamic_field_pairs
    )
    for imported_name, modules in sorted(
        imported_origins.items(),
        key=lambda item: (item[0].startswith("_"), item[0]),
    ):
        if len(modules) > 1 or imported_name in local_symbols:
            origins = ", ".join(sorted(modules))
            raise GenerationError(
                f"generated symbol collision for {imported_name!r} from {origins}"
            )
    scalar_readers = {
        _SCALAR_READERS[field.type.base_type]
        for item in local_objects
        for field in item.fields
        if field.type.base_type in _SCALARS
    }
    for item in local_objects:
        for pair in context.union_pairs(item):
            if pair.vector:
                scalar_readers.add(
                    _SCALAR_READERS[pair.enum.underlying_type.base_type]
                )
    if any(
        not item.is_struct
        and any(field.type.base_type in _SCALARS for field in item.fields)
        for item in local_objects
    ):
        scalar_readers.add(("_UINT16", "<H"))
    struct_unpackers = [
        unpacker
        for item in local_objects
        if (unpacker := _struct_unpacker(context, item)) is not None
    ]
    lines = [
        _GENERATED_HEADER,
        f"# Source: {declaration_file}",
        "from __future__ import annotations",
        "",
        "import struct",
        *(
            [f"from typing import {', '.join(typing_imports)}"]
            if typing_imports
            else []
        ),
        "",
        "import msgspec",
        "import numpy as np",
        "import numpy.typing as npt",
        "",
        "from msgspec_flatbuffers import (",
        "    InvalidBufferError,",
        "    OpenIntEnum,",
        "    StringVector,",
        "    StructVector,",
        "    StructView,",
        "    TableVector,",
        "    TableView,",
        *(
            ["    DynamicValue,", "    DynamicView,"]
            if has_dynamic
            else []
        ),
        *(["    register_dynamic_type,"] if dynamic_extension else []),
        *(["    UnionDispatch,", "    UnionVector,"] if has_unions else []),
        ")",
        "from msgspec_flatbuffers._native import NativePlan as _NativePlan",
    ]
    for module in sorted(set(object_imports) | set(enum_imports)):
        names = sorted(object_imports.get(module, set()) | enum_imports.get(module, set()))
        lines.append(f"from {module} import {', '.join(names)}")

    if has_byte_vector_helpers:
        lines.extend(("", '_NestedViewT = TypeVar("_NestedViewT", bound=TableView)'))
    if scalar_readers or struct_unpackers:
        lines.append("")
    for reader, fmt in sorted(scalar_readers):
        lines.append(f"{reader} = struct.Struct({fmt!r})")
    for unpacker, fmt in struct_unpackers:
        lines.append(f"{unpacker} = struct.Struct({fmt!r})")
    lines.extend(
        ("", f"_FB_NATIVE_MODULE = _NativePlan({_native_module_plan_bytes(context)!r})")
    )

    for item in local_enums:
        lines.extend(("", "", *_render_enum(context, item)))
    for item, pair in dynamic_field_pairs:
        lines.extend(("", "", *_render_dynamic_value_type(item, pair)))
    for item in local_objects:
        lines.extend(("", "", *_render_model(context, item, item is root)))
    bound_objects = {
        item.name: item
        for item in context.schema.objects
        if item.declaration_file == declaration_file
        or (
            (module := _definition_module(
                item.name,
                item.declaration_file,
                context.package_prefix,
            ))
            in object_imports
            and _short_name(item.name) in object_imports[module]
        )
    }
    if bound_objects:
        lines.extend(("", "", "_FB_NATIVE_MODULE.bind_types({"))
        lines.extend(
            f"    {name!r}: {_short_name(item.name)},"
            for name, item in sorted(bound_objects.items())
        )
        lines.append("})")
    for item in local_objects:
        lines.extend(("", "", *_render_view(context, item, item is root)))
    for item in local_enums:
        if item.is_union:
            lines.extend(("", "", *_render_union_dispatch(context, item)))
    if root is not None:
        lines.extend(("", "", *_render_root_builder(context, root)))
    if dynamic_extension and root is not None:
        root_name = _short_name(root.name)
        lines.extend(
            (
                "",
                "",
                f"register_dynamic_type({root_name}, {root_name}View)",
            )
        )

    exported = [
        *(_short_name(item.name) for item in local_enums),
        *(
            name
            for item in local_objects
            for name in (_short_name(item.name), f"{_short_name(item.name)}View")
        ),
    ]
    if root is not None:
        exported.append(f"build_{_snake_case(_short_name(root.name))}")
    lines.extend(("", "", f"__all__ = {exported!r}", ""))
    return "\n".join(lines)


def _source_declaration(source: Path, project_root: Path) -> str:
    try:
        relative = source.relative_to(project_root)
    except ValueError as error:
        raise GenerationError(
            f"schema {source} is outside project root {project_root}"
        ) from error
    return f"//{relative.as_posix()}"


def generate(
    schema_path: StrPath,
    output_dir: StrPath,
    *,
    include_dirs: Iterable[StrPath] = (),
    flatc: StrPath = "flatc",
    project_root: StrPath | None = None,
    package: str | None = None,
) -> Path:
    """Generate one Python module for one FlatBuffers IDL file."""

    source = Path(schema_path).resolve()
    root = source.parent if project_root is None else Path(project_root).resolve()
    schema = compile_schema(
        source,
        include_dirs=include_dirs,
        flatc=flatc,
        project_root=root,
    )
    declaration_file = _source_declaration(source, root)
    definitions = [
        item
        for item in [*schema.objects, *schema.enums]
        if item.declaration_file == declaration_file
    ]
    if not definitions:
        raise GenerationError(
            f"compiled schema does not contain declarations for {declaration_file}"
        )

    namespaces = {_namespace(item.name) for item in definitions}
    if len(namespaces) != 1:
        raise GenerationError(
            "one .fbs file declaring multiple namespaces is not supported yet"
        )
    namespace = next(iter(namespaces))
    prefix = tuple(part for part in (package or "").split(".") if part)
    package_parts = (*(_snake_case(part) for part in prefix), *(_snake_case(part) for part in namespace))
    target_dir = Path(output_dir).resolve().joinpath(*package_parts)
    target_dir.mkdir(parents=True, exist_ok=True)

    current = Path(output_dir).resolve()
    for part in package_parts:
        current /= part
        init = current / "__init__.py"
        if not init.exists():
            init.write_text("", encoding="utf-8")

    target = target_dir / f"{_snake_case(source.stem)}.py"
    if target.exists():
        expected_header = [_GENERATED_HEADER, f"# Source: {declaration_file}"]
        actual_header = target.read_text(encoding="utf-8").splitlines()[:2]
        if actual_header != expected_header:
            raise GenerationError(f"refusing to overwrite non-generated file: {target}")

    target.write_text(
        render_module(schema, declaration_file, package_prefix=prefix),
        encoding="utf-8",
    )
    return target


