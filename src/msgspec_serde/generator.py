def _nested_cache_load_lines(
    context: _Context,
    field: FieldDefinition,
    nested: ObjectDefinition,
    *,
    target: str,
    indent: str,
    size_prefixed: bool,
) -> list[str]:
    nested_name = context.view_name(nested)
    cache_slot = _nested_cache_slot(field, size_prefixed=size_prefixed)
    payload_property = _raw_property_name(field)
    lines = [
        f"{indent}try:",
        f"{indent}    {target} = self.{cache_slot}",
        f"{indent}except AttributeError:",
        f"{indent}    payload = self.{payload_property}",
    ]
    if not field.required:
        lines.extend(
            [
                f"{indent}    if payload is None:",
                f"{indent}        {target} = None",
                f"{indent}    else:",
            ]
        )
    load_indent = indent if field.required else f"{indent}    "
    lines.extend(
        [
            f"{load_indent}    {target} = _decode_flatbuffer(",
            f"{load_indent}        payload, type={nested_name},",
            f"{load_indent}        size_prefixed={size_prefixed!r},",
            f"{load_indent}    )",
        ]
    )
    lines.append(f"{indent}    self.{cache_slot} = {target}")
    return lines


def _nested_view_members(
    context: _Context,
    field: FieldDefinition,
    nested: ObjectDefinition,
) -> list[str]:
    property_name = _identifier(field.name)
    nested_name = context.view_name(nested)
    return_type = _view_return_type(nested_name, field)
    return [
        "    @property",
        f"    def {property_name}(self) -> {return_type}:",
        *_nested_cache_load_lines(
            context,
            field,
            nested,
            target="value",
            indent="        ",
            size_prefixed=False,
        ),
        "        return value",
        "",
        f"    def {property_name}_view(",
        "        self,",
        "        *,",
        "        size_prefixed: bool = False,",
        f"    ) -> {return_type}:",
        "        if not size_prefixed:",
        f"            return self.{property_name}",
        *_nested_cache_load_lines(
            context,
            field,
            nested,
            target="value",
            indent="        ",
            size_prefixed=True,
        ),
        "        return value",
    ]


def _union_cache_load_lines(
    context: _Context,
    pair: _UnionPair,
    *,
    target: str,
    indent: str,
) -> list[str]:
    field = pair.value_field
    slot = _cache_slot(field)
    property_name = _identifier(field.name)
    dispatch = context.union_dispatch_name(pair.enum)
    annotation = _view_return_type(_union_view_type(context, pair), field)
    lines = [
        f"{indent}try:",
        f"{indent}    {target} = self.{slot}",
        f"{indent}except AttributeError:",
        f"{indent}    {target} = cast(",
        f"{indent}        {annotation},",
        f"{indent}        self._read_union(",
        f"{indent}            {field.offset}, int(self.{property_name}_type), {dispatch}",
        f"{indent}        ),",
        f"{indent}    )",
    ]
    lines.extend(_required_field_check(field, target=target, indent=f"{indent}    "))
    lines.append(f"{indent}    self.{slot} = {target}")
    return lines


def _union_view_property(context: _Context, pair: _UnionPair) -> list[str]:
    field = pair.value_field
    property_name = _identifier(field.name)
    annotation = _view_return_type(_union_view_type(context, pair), field)
    return [
        "    @property",
        f"    def {property_name}(self) -> {annotation}:",
        *_union_cache_load_lines(
            context,
            pair,
            target="value",
            indent="        ",
        ),
        "        return value",
    ]


def _union_vector_cache_load_lines(
    context: _Context,
    pair: _UnionPair,
    *,
    target: str,
    indent: str,
) -> list[str]:
    field = pair.value_field
    type_field = pair.type_field
    slot = _cache_slot(field)
    type_property = _identifier(type_field.name)
    dispatch = context.union_dispatch_name(pair.enum)
    reader, _ = _SCALAR_READERS[pair.enum.underlying_type.base_type]
    lines = [
        f"{indent}try:",
        f"{indent}    {target} = self.{slot}",
        f"{indent}except AttributeError:",
        f"{indent}    types = self.{type_property}",
        f"{indent}    info = self._vector_info({field.offset}, 4)",
        f"{indent}    if types is None and info is None:",
    ]
    if field.required:
        lines.append(
            f"{indent}        raise InvalidBufferError("
            f'"required field {field.name!r} is absent")'
        )
    else:
        lines.append(f"{indent}        {target} = None")
    lines.extend(
        [
            f"{indent}    elif types is None or info is None:",
            (
                f"{indent}        raise InvalidBufferError("
                f'"union vector {field.name!r} type/value presence differs")'
            ),
            f"{indent}    else:",
            f"{indent}        start, length = info",
            f"{indent}        {target} = UnionVector(",
            f"{indent}            self._buffer, types, start, length, {reader}, {dispatch}",
            f"{indent}        )",
            f"{indent}    self.{slot} = {target}",
        ]
    )
    return lines


def _union_vector_property(context: _Context, pair: _UnionPair) -> list[str]:
    field = pair.value_field
    name = _identifier(field.name)
    annotation = _view_return_type(
        f"UnionVector[{_union_view_type(context, pair)} | None]",
        field,
    )
    return [
        "    @property",
        f"    def {name}(self) -> {annotation}:",
        *_union_vector_cache_load_lines(
            context,
            pair,
            target="value",
            indent="        ",
        ),
        "        return value",
    ]


def _render_view_field_property(
    context: _Context,
    item: ObjectDefinition,
    field: FieldDefinition,
    union_pair: _UnionPair | None,
    *,
    raw: bool,
) -> list[str]:
    if union_pair is not None:
        if union_pair.vector:
            return _union_vector_property(context, union_pair)
        return _union_view_property(context, union_pair)
    if raw:
        return _complex_view_property(
            context,
            field,
            name=_raw_property_name(field),
        )
    if field.type.base_type in _SCALARS:
        return _scalar_view_property(context, field, item.is_struct)
    if not item.is_struct:
        return _complex_view_property(context, field)
    if field.type.base_type is BaseType.ARRAY:
        return _array_view_property(context, field)
    if field.type.base_type is not BaseType.OBJECT:
        raise GenerationError(
            f"unsupported struct field type {field.type.base_type.name}"
        )

    nested = context.object_for(field.type)
    if not nested.is_struct:
        raise GenerationError("FlatBuffers structs may only contain structs")
    property_name = _identifier(field.name)
    nested_name = _short_name(nested.name)
    return [
        "    @property",
        f"    def {property_name}(self) -> {nested_name}View:",
        *_complex_cache_load_lines(
            context,
            field,
            target="value",
            indent="        ",
        ),
        "        return value",
    ]


def _render_view(context: _Context, item: ObjectDefinition, root: bool) -> list[str]:
    name = _short_name(item.name)
    base = "_FbStructView" if item.is_struct else "_FbTableView"
    fields = _field_order(item)
    union_pairs = context.union_pairs(item)
    union_pairs_by_value_id = {pair.value_field.id: pair for pair in union_pairs}
    dynamic_pairs = context.dynamic_pairs(item)
    dynamic_pairs_by_value_id = {pair.value_field.id: pair for pair in dynamic_pairs}
    dynamic_pairs_by_type_id = {pair.type_field.id: pair for pair in dynamic_pairs}
    nested_targets = {
        field.id: target
        for field in fields
        if (target := context.nested_target(item, field)) is not None
    }
    raw_field_ids = (
        set(nested_targets)
        | dynamic_pairs_by_value_id.keys()
        | dynamic_pairs_by_type_id.keys()
    )
    cached_fields = [field for field in fields if field.type.base_type not in _SCALARS]
    byte_vector_fields = [
        field
        for field in fields
        if _is_byte_vector(field.type)
        and field.id not in nested_targets
        and field.id not in dynamic_pairs_by_value_id
    ]
    property_names = {_identifier(field.name) for field in fields}
    for field in byte_vector_fields:
        method_name = f"{_identifier(field.name)}_as"
        if method_name in property_names:
            raise GenerationError(
                f"generated byte-vector helper {method_name!r} conflicts with a field"
            )
    for field in fields:
        if field.id in nested_targets:
            method_name = f"{_identifier(field.name)}_view"
            if method_name in property_names:
                raise GenerationError(
                    f"generated nested helper {method_name!r} conflicts with a field"
                )
        if field.id in raw_field_ids:
            raw_name = _raw_property_name(field)
            if raw_name in property_names:
                raise GenerationError(
                    f"generated raw property {raw_name!r} conflicts with a field"
                )
    cache_slots = [_cache_slot(field) for field in cached_fields]
    for field in fields:
        if field.id in nested_targets:
            cache_slots.extend(
                (
                    _nested_cache_slot(field, size_prefixed=False),
                    _nested_cache_slot(field, size_prefixed=True),
                )
            )
    cache_slots.extend(_dynamic_cache_slot(pair.value_field) for pair in dynamic_pairs)
    model_offset = "_struct_offset" if item.is_struct else "_table_offset"
    lines = [f"class {name}View({base}):"]
    lines.extend(_documentation(item.documentation))
    lines.append(f"    __slots__ = {tuple(cache_slots)!r}")
    if item.is_struct:
        lines.append(f"    __flatbuffer_size__ = {item.byte_size}")
    elif root and context.schema.file_identifier is not None:
        lines.append(
            f"    __flatbuffer_identifier__ = {context.schema.file_identifier.encode()!r}"
        )

    for field in fields:
        lines.append("")
        pair = union_pairs_by_value_id.get(field.id)
        lines.extend(
            _render_view_field_property(
                context,
                item,
                field,
                pair,
                raw=field.id in raw_field_ids,
            )
        )

    for field in byte_vector_fields:
        lines.append("")
        lines.extend(_byte_vector_as_method(field))

    for field in fields:
        target = nested_targets.get(field.id)
        if target is not None:
            lines.append("")
            lines.extend(_nested_view_members(context, field, target))

    for pair in dynamic_pairs:
        lines.append("")
        lines.extend(_dynamic_view_property(item, pair))

    lines.extend(
        (
            "",
            "    @overload",
            "    def to_model(",
            "        self,",
            "        *,",
            "        dynamic_overrides: DynamicModelOverrides | None = None,",
            f"    ) -> {name}: ...",
            "",
            "    @overload",
            f"    def to_model[_ModelT: {name}](",
            "        self,",
            "        model_type: type[_ModelT],",
            "        *,",
            "        dynamic_overrides: DynamicModelOverrides | None = None,",
            "    ) -> _ModelT: ...",
            "",
            "    def to_model(",
            "        self,",
            f"        model_type: type[{name}] = {name},",
            "        *,",
            "        dynamic_overrides: DynamicModelOverrides | None = None,",
            f"    ) -> {name}:",
            f"        if model_type is {name} and dynamic_overrides is None:",
            "            return _FB_NATIVE_MODULE.unpack_view(",
            f"                {item.name!r},",
            "                self._buffer,",
            f"                self.{model_offset},",
            "            )",
            f"        native_types = None if model_type is {name} else _resolve_model_types(",
            f"            _FB_NATIVE_MODULE, {name}, model_type",
            "        )",
            "        return _FB_NATIVE_MODULE.unpack_view(",
            f"            {item.name!r},",
            "            self._buffer,",
            f"            self.{model_offset},",
            "            model_types=native_types,",
            "            dynamic_overrides=dynamic_overrides,",
            "        )",
        )
    )
    return lines


def _native_plan_default(field: FieldDefinition) -> bool | int | float | None:
    if field.optional:
        return None
    if field.type.base_type is BaseType.BOOL:
        return bool(field.default_integer)
    if field.type.base_type in (BaseType.FLOAT, BaseType.DOUBLE):
        return field.default_real
    if field.type.base_type in _SCALARS:
        return field.default_integer
    return None


def _native_field_plan(
    context: _Context,
    owner: ObjectDefinition,
    field: FieldDefinition,
    union_pair: _UnionPair | None,
    dynamic_pair: _DynamicPair | None,
) -> dict[str, object]:
    if field.offset64:
        raise GenerationError(
            f"64-bit offset field {owner.name}.{field.name} is unsupported"
        )
    type_ref = field.type
    plan: dict[str, object] = {
        "name": _identifier(field.name),
        "slot": field.id,
        "offset": field.offset,
        "optional": field.optional,
        "required": field.required,
        "default": _native_plan_default(field),
        "serde_nullable": field.optional,
    }
    if field.key:
        plan["key"] = True
    if union_pair is not None:
        plan.update(
            kind="union_vector" if union_pair.vector else "union",
            type_slot=union_pair.type_field.id,
            type_scalar=context.scalar_spec(
                union_pair.enum.underlying_type.base_type
            ).runtime_name,
            arms=[
                {"tag": arm.tag, "target": arm.object.name} for arm in union_pair.arms
            ],
        )
        if union_pair.vector:
            plan["serde_element_nullable"] = True
        return plan
    if dynamic_pair is not None:
        plan.update(
            kind="dynamic",
            type_slot=dynamic_pair.type_field.id,
            allowed_prefix=dynamic_pair.allowed_prefix,
            dynamic_type=_dynamic_value_type_key(owner, dynamic_pair),
        )
        return plan
    nested = context.nested_target(owner, field)
    if nested is not None:
        plan.update(kind="nested", target=nested.name)
        return plan
    if type_ref.base_type in _SCALARS:
        plan.update(
            kind="scalar",
            scalar=context.scalar_spec(type_ref.base_type).runtime_name,
        )
        enum = context.enum_for(type_ref)
        if enum is not None:
            plan["enum_type"] = enum.name
    elif type_ref.base_type is BaseType.STRING:
        plan["kind"] = "string"
    elif type_ref.base_type is BaseType.OBJECT:
        target = context.object_for(type_ref)
        plan.update(
            kind="struct" if target.is_struct else "table",
            target=target.name,
        )
    elif type_ref.base_type is BaseType.VECTOR:
        if _is_byte_vector(type_ref):
            plan["kind"] = "vector_byte"
        elif type_ref.element in _SCALARS:
            plan.update(
                kind="vector_scalar",
                scalar=context.scalar_spec(type_ref.element).runtime_name,
            )
            enum = context.enum_for(type_ref)
            if enum is not None:
                plan["enum_type"] = enum.name
        elif type_ref.element is BaseType.STRING:
            plan["kind"] = "vector_string"
        elif type_ref.element is BaseType.OBJECT:
            target = context.object_for(type_ref)
            plan.update(
                kind="vector_struct" if target.is_struct else "vector_table",
                target=target.name,
            )
        else:  # pragma: no cover - rejected by earlier generation checks
            raise GenerationError(
                f"unsupported native vector element {type_ref.element.name}"
            )
    elif type_ref.base_type is BaseType.ARRAY:
        plan.update(
            fixed_length=type_ref.fixed_length,
            element_size=type_ref.element_size,
        )
        if type_ref.element in _SCALARS:
            plan.update(
                kind="array_scalar",
                scalar=context.scalar_spec(type_ref.element).runtime_name,
            )
            enum = context.enum_for(type_ref)
            if enum is not None:
                plan["enum_type"] = enum.name
        elif type_ref.element is BaseType.OBJECT:
            target = context.object_for(type_ref)
            if not target.is_struct:
                raise GenerationError("FlatBuffers arrays may only contain structs")
            plan.update(
                kind="array_struct",
                target=target.name,
                element_size=target.byte_size,
            )
        else:
            raise GenerationError(
                f"unsupported native array element {type_ref.element.name}"
            )
    else:  # pragma: no cover - rejected by earlier generation checks
        raise GenerationError(
            f"unsupported native field type {type_ref.base_type.name}"
        )
    return plan


def _native_module_plan_bytes(context: _Context) -> bytes:
    objects: list[dict[str, object]] = []
    for item in context.schema.objects:
        if item.name not in context.reachable_object_names:
            continue
        union_pairs = context.union_pairs(item)
        dynamic_pairs = context.dynamic_pairs(item)
        union_by_value = {pair.value_field.id: pair for pair in union_pairs}
        dynamic_by_value = {pair.value_field.id: pair for pair in dynamic_pairs}
        hidden_type_field_ids = _hidden_type_field_ids(
            union_pairs,
            dynamic_pairs,
        )
        model_fields = [
            field
            for field in _field_order(item)
            if field.id not in hidden_type_field_ids
        ]
        fields = [
            _native_field_plan(
                context,
                item,
                field,
                union_by_value.get(field.id),
                dynamic_by_value.get(field.id),
            )
            for field in model_fields
        ]
        is_union_arm = context.is_union_arm(item)
        objects.append(
            {
                "name": item.name,
                "is_struct": item.is_struct,
                "byte_size": item.byte_size,
                "min_alignment": item.min_alignment,
                "fields": fields,
                "serde_fields": [
                    {
                        "attr_name": _identifier(field.name),
                        "encode_name": field.name,
                    }
                    for field in model_fields
                ],
                "serde_tag_field": _MSGSPEC_TAG_FIELD if is_union_arm else None,
                "serde_tag": item.name if is_union_arm else None,
            }
        )
    return msgspec.msgpack.encode({"version": 2, "objects": objects})


def _local_root(
    schema: Schema,
    local_names: frozenset[str],
) -> ObjectDefinition | None:
    if schema.root_table is None:
        return None
    root = schema.object(schema.root_table)
    return root if root.name in local_names else None


def _dynamic_extension_enabled(
    local_objects: Sequence[ObjectDefinition],
    root: ObjectDefinition | None,
) -> bool:
    enabled = False
    for item in local_objects:
        if not _has_marker_attribute(item, "dynamic_extension"):
            continue
        if item.is_struct or item is not root:
            raise GenerationError(
                f"dynamic extension {item.name} must be this file's root table"
            )
        enabled = True
    return enabled


def _reexported_symbols(
    object_imports: dict[str, set[str]],
    enum_imports: dict[str, set[str]],
    local_symbols: set[str],
) -> dict[str, str | None]:
    reexports: dict[str, str | None] = {}
    for module in sorted(object_imports.keys() | enum_imports.keys()):
        names = object_imports.get(module, set()) | enum_imports.get(module, set())
        for name in names - local_symbols:
            if name not in reexports:
                reexports[name] = module
            elif reexports[name] != module:
                reexports[name] = None
    return reexports


def _bound_type_names(
    context: _Context,
    dynamic_field_pairs: Sequence[tuple[ObjectDefinition, _DynamicPair]],
) -> dict[str, str]:
    bound_types = {
        item.name: context.model_name(item)
        for item in context.schema.objects
        if item.name in context.reachable_object_names
    }
    bound_types.update(
        {
            enum.name: context.enum_name(enum)
            for enum in context.schema.enums
            if enum.name in context.reachable_enum_names
        }
    )
    bound_types.update(
        {
            _dynamic_value_type_key(item, pair): _dynamic_value_type_name(item, pair)
            for item, pair in dynamic_field_pairs
        }
    )
    return bound_types


def render_module(
    schema: Schema,
    declaration_file: str,
    *,
    package_prefix: Iterable[str] = (),
    definition_names: frozenset[str] | None = None,
    gen_onefile: bool = False,
) -> str:
    """Render Python source for definitions from one declaring file.

    Args:
        schema: The normalized schema to render.
        declaration_file: The source filename recorded in the schema, including
            its leading ``//``.
        package_prefix: Optional Python package components prepended to generated
            imports.
        definition_names: Fully qualified definitions to render. All definitions
            from ``declaration_file`` are rendered by default.
        gen_onefile: Whether all definitions share one generated module.

    Returns:
        A complete generated Python module.

    Raises:
        GenerationError: The selection is empty, ambiguous, or unsupported.

    Example:
        Render every definition declared by one schema file:

        >>> source = render_module(schema, "//schemas/monster.fbs")
        >>> source.startswith("# Generated by msgspec-serde")
        True
    """

    prefix = tuple(_snake_case(part) for part in package_prefix)

    def is_local(item: ObjectDefinition | EnumDefinition) -> bool:
        return item.declaration_file == declaration_file and (
            definition_names is None or item.name in definition_names
        )

    local_objects = [item for item in schema.objects if is_local(item)]
    local_enums = [item for item in schema.enums if is_local(item)]
    local_tables = [item for item in local_objects if not item.is_struct]
    local_structs = [item for item in local_objects if item.is_struct]
    local_fields = [(item, field) for item in local_objects for field in item.fields]
    local_definitions = [*local_objects, *local_enums]
    if not local_definitions:
        raise GenerationError(f"no definitions declared in {declaration_file!r}")
    _validate_member_names(local_objects, local_enums)
    local_symbols = _local_symbols(local_objects, local_enums)
    local_names = frozenset(item.name for item in local_definitions)
    context = _Context(
        schema,
        prefix,
        local_names,
        gen_onefile,
    )
    dynamic_field_pairs = [
        (item, pair) for item in local_objects for pair in context.dynamic_pairs(item)
    ]
    dynamic_value_field_ids = {
        (item.name, pair.value_field.id) for item, pair in dynamic_field_pairs
    }
    has_dynamic = bool(dynamic_field_pairs)
    has_byte_vector_helpers = any(
        _is_byte_vector(field.type)
        and context.nested_target(item, field) is None
        and (item.name, field.id) not in dynamic_value_field_ids
        for item, field in local_fields
    )
    has_nested_flatbuffers = any(
        context.nested_target(item, field) is not None for item, field in local_fields
    )
    needs_flatbuffer_decoder = has_byte_vector_helpers or has_nested_flatbuffers
    union_pairs = [pair for item in local_objects for pair in context.union_pairs(item)]
    has_union_definitions = any(item.is_union for item in local_enums)
    has_scalar_unions = any(not pair.vector for pair in union_pairs)
    has_union_vectors = any(pair.vector for pair in union_pairs)
    has_numpy_fields = any(
        _is_numpy_model_field(context, field) for _, field in local_fields
    )
    has_string_vectors = any(
        field.type.base_type is BaseType.VECTOR
        and field.type.element is BaseType.STRING
        for _, field in local_fields
    )
    vector_object_targets = [
        context.object_for(field.type)
        for _, field in local_fields
        if field.type.base_type is BaseType.VECTOR
        and field.type.element is BaseType.OBJECT
    ]
    array_object_targets = [
        context.object_for(field.type)
        for _, field in local_fields
        if field.type.base_type is BaseType.ARRAY
        and field.type.element is BaseType.OBJECT
    ]
    table_vector_keys = [
        context.key_field(target)
        for target in vector_object_targets
        if not target.is_struct
    ]
    has_struct_vectors = any(
        target.is_struct for target in vector_object_targets
    ) or any(target.is_struct for target in array_object_targets)
    has_table_vectors = any(key is None for key in table_vector_keys)
    has_table_maps = any(key is not None for key in table_vector_keys)
    needs_invalid_buffer_error = any(
        (
            any(
                field.type.base_type in _SCALARS or field.required
                for field in _field_order(item)
            )
            or context.union_pairs(item)
            or context.dynamic_pairs(item)
        )
        for item in local_tables
    )
    typing_imports = {"overload"} if local_objects else set()
    if has_byte_vector_helpers:
        typing_imports.update(("Any", "TypeVar"))
    if has_scalar_unions:
        typing_imports.add("cast")

    root = _local_root(schema, local_names)
    dynamic_extension = _dynamic_extension_enabled(local_objects, root)

    object_imports, enum_imports = context.referenced_definitions(
        local_objects,
        local_enums,
    )
    import_modules = set(object_imports) | set(enum_imports)
    enum_dependency_modules = set(enum_imports)
    dynamic_value_names = [
        _dynamic_value_type_name(item, pair) for item, pair in dynamic_field_pairs
    ]
    for dynamic_name in dynamic_value_names:
        if dynamic_name in local_symbols:
            raise GenerationError(
                f"generated dynamic value type {dynamic_name!r} conflicts with "
                "another generated symbol"
            )
        local_symbols.add(dynamic_name)
    reexports = _reexported_symbols(
        object_imports,
        enum_imports,
        local_symbols,
    )
    scalar_readers = {
        _SCALAR_READERS[field.type.base_type]
        for _, field in local_fields
        if field.type.base_type in _SCALARS
    }
    for pair in union_pairs:
        if pair.vector:
            scalar_readers.add(_SCALAR_READERS[pair.enum.underlying_type.base_type])
    if any(
        any(field.type.base_type in _SCALARS for field in item.fields)
        for item in local_tables
    ):
        scalar_readers.add(("_UINT16", "<H"))
    runtime_imports = []
    if local_objects:
        runtime_imports.append("DynamicModelOverrides")
    if needs_invalid_buffer_error:
        runtime_imports.append("InvalidBufferError")
    if local_enums:
        runtime_imports.append("OpenIntEnum as _FbOpenIntEnum")
    if has_string_vectors:
        runtime_imports.append("StringVector")
    if has_struct_vectors:
        runtime_imports.append("StructVector")
    if local_structs:
        runtime_imports.append("StructView as _FbStructView")
    if has_table_vectors:
        runtime_imports.append("TableVector")
    if has_table_maps:
        runtime_imports.append("TableMap")
    if local_tables:
        runtime_imports.append("TableView as _FbTableView")
    if has_dynamic:
        runtime_imports.extend(("DynamicValue as _FbDynamicValue", "DynamicView"))
    if dynamic_extension:
        runtime_imports.append("register_dynamic_type as _register_dynamic_type")
    if has_union_definitions:
        runtime_imports.append("UnionDispatch as _FbUnionDispatch")
    if has_union_vectors:
        runtime_imports.append("UnionVector")
    standard_imports = []
    if scalar_readers:
        standard_imports.append("import struct")
    if typing_imports:
        standard_imports.append(
            f"from typing import {', '.join(sorted(typing_imports))}"
        )
    third_party_imports = []
    if local_objects:
        third_party_imports.append("import msgspec")
    if has_numpy_fields:
        third_party_imports.extend(("import numpy as np", "import numpy.typing as npt"))

    lines = [
        _GENERATED_HEADER,
        f"# Source: {declaration_file}",
        "from __future__ import annotations",
    ]
    if standard_imports:
        lines.extend(("", *standard_imports))
    if third_party_imports:
        lines.extend(("", *third_party_imports))
    lines.extend(
        (
            "",
            "from msgspec_serde import _check_generated_code_version",
            "",
            f"__msgspec_serde_generated_version__ = {_GENERATOR_VERSION!r}",
            "_check_generated_code_version(__msgspec_serde_generated_version__)",
            "",
            "from msgspec_serde import (  # noqa: E402",
            *(f"    {name}," for name in runtime_imports),
            ")",
        )
    )
    if local_objects:
        lines.extend(
            (
                "from msgspec_serde._models import resolve_model_types as _resolve_model_types  # noqa: E402",
                "from msgspec_serde._native import NativePlan as _NativePlan  # noqa: E402",
            )
        )
    if needs_flatbuffer_decoder:
        lines.append(
            "from msgspec_serde._flatbuffer import decode as _decode_flatbuffer  # noqa: E402"
        )
    if local_tables:
        lines.append(
            "from msgspec_serde._flatbuffer import register_type as _register_flatbuffer_type  # noqa: E402"
        )
    if enum_dependency_modules:
        lines.append("")
        lines.extend(
            f"import {module} as {context.module_alias(module)}"
            for module in sorted(enum_dependency_modules)
        )
    if has_byte_vector_helpers:
        lines.extend(("", '_NestedViewT = TypeVar("_NestedViewT", bound=_FbTableView)'))
    if scalar_readers:
        lines.append("")
    for reader, fmt in sorted(scalar_readers):
        lines.append(f"{reader} = struct.Struct({fmt!r})")
    if local_objects:
        lines.extend(
            (
                "",
                f"_FB_NATIVE_MODULE = _NativePlan({_native_module_plan_bytes(context)!r})",
            )
        )

    for item in local_enums:
        lines.extend(("", "", *_render_enum(context, item)))
    for item, pair in dynamic_field_pairs:
        lines.extend(("", "", *_render_dynamic_value_type(item, pair)))
    for item in local_objects:
        lines.extend(("", "", *_render_model(context, item)))
    for item in local_objects:
        lines.extend(("", "", *_render_view(context, item, item is root)))
    object_dependency_modules = import_modules - enum_dependency_modules
    if object_dependency_modules:
        lines.extend(("", ""))
        lines.extend(
            f"import {module} as {context.module_alias(module)}"
            for module in sorted(object_dependency_modules)
        )
    reexport_lines = [
        f"{name} = {context.module_alias(module)}.{name}"
        for name, module in sorted(reexports.items())
        if module is not None
    ]
    if reexport_lines:
        lines.extend(("", "", *reexport_lines))
    for item in local_enums:
        if item.is_union:
            lines.extend(("", "", *_render_union_dispatch(context, item)))
    bound_types = (
        _bound_type_names(context, dynamic_field_pairs) if local_objects else {}
    )
    if bound_types:
        lines.extend(("", "", "_FB_NATIVE_MODULE.bind_types({"))
        lines.extend(
            f"    {name!r}: {type_name},"
            for name, type_name in sorted(bound_types.items())
        )
        lines.append("})")
    for item in local_tables:
        identifier = (
            repr(context.schema.file_identifier)
            if item is root and context.schema.file_identifier is not None
            else "None"
        )
        lines.extend(
            (
                "",
                "",
                f"_register_flatbuffer_type({_short_name(item.name)}, _FB_NATIVE_MODULE, {item.name!r}, {identifier})",
            )
        )
    if dynamic_extension and root is not None:
        root_name = _short_name(root.name)
        lines.extend(
            (
                "",
                "",
                f"_register_dynamic_type({root.name!r}, {root_name}, {root_name}View)",
            )
        )

    exported = [
        *(_short_name(item.name) for item in local_enums),
        *dynamic_value_names,
        *(
            name
            for item in local_objects
            for name in (_short_name(item.name), f"{_short_name(item.name)}View")
        ),
    ]
    lines.extend(("", "", f"__all__ = {exported!r}", ""))
    return "\n".join(lines)


def _source_declaration(source: Path, project_root: Path) -> str:
    try:
        relative = source.relative_to(project_root)
    except ValueError as error:
        raise GenerationError(
            f"schema {source} is outside project root {project_root}"
        ) from error
    return f"//{relative.as_posix()}"


def generate(
    schema_path: StrPath,
    output_dir: StrPath,
    *,
    include_dirs: Iterable[StrPath] = (),
    flatc: StrPath = "flatc",
    project_root: StrPath | None = None,
    package: str | None = None,
    gen_onefile: bool = False,
) -> Path:
    """Generate Python modules from a FlatBuffers IDL file.

    Args:
        schema_path: The ``.fbs`` file to compile and generate.
        output_dir: The directory that receives generated Python packages.
        include_dirs: Additional directories searched for included schemas.
        flatc: The ``flatc`` executable name or path.
        project_root: The root used for filenames stored by ``flatc``. The
            schema's parent directory is used by default.
        package: An optional Python package prefix.
        gen_onefile: Whether to place all definitions from the schema in one
            module.

    Returns:
        The generated module path for the root definition, or the first module
        when the schema has no root table.

    Raises:
        FlatcError: The schema compiler fails.
        GenerationError: The schema cannot be represented or a generated path
            would overwrite a non-generated file.
        OSError: An input cannot be read or an output cannot be written.

    Example:
        Generate importable modules beneath ``generated``:

        >>> module_path = generate(
        ...     "schemas/monster.fbs",
        ...     "generated",
        ...     package="models",
        ... )
        >>> module_path.suffix
        '.py'
    """

    source = Path(schema_path).resolve()
    root = source.parent if project_root is None else Path(project_root).resolve()
    schema = compile_schema(
        source,
        include_dirs=include_dirs,
        flatc=flatc,
        project_root=root,
    )
    declaration_file = _source_declaration(source, root)
    definitions = [
        item
        for item in [*schema.objects, *schema.enums]
        if item.declaration_file == declaration_file
    ]
    if not definitions:
        raise GenerationError(
            f"compiled schema does not contain declarations for {declaration_file}"
        )

    prefix = tuple(part for part in (package or "").split(".") if part)
    output_root = Path(output_dir).resolve()
    prefix_parts = tuple(_snake_case(part) for part in prefix)
    if gen_onefile:
        module_specs: list[tuple[str | None, tuple[str, ...], str]] = [
            (None, (), _snake_case(source.stem))
        ]
    else:
        module_specs = [
            (
                item.name,
                _namespace(item.name),
                _snake_case(_short_name(item.name)),
            )
            for item in sorted(definitions, key=lambda item: item.name)
        ]
    targets: dict[Path, str] = {}
    rendered_modules: list[tuple[str | None, Path, str]] = []
    for definition_name, namespace_parts, module_name in module_specs:
        package_parts = (
            *prefix_parts,
            *(_snake_case(part) for part in namespace_parts),
        )
        target = output_root.joinpath(*package_parts, f"{module_name}.py")
        source_name = definition_name or declaration_file
        previous = targets.get(target)
        if previous is not None:
            raise GenerationError(
                f"definitions {previous!r} and {source_name!r} both generate "
                f"module {target.relative_to(output_root)}"
            )
        targets[target] = source_name
        selected_names = (
            None if definition_name is None else frozenset((definition_name,))
        )
        source_text = render_module(
            schema,
            declaration_file,
            package_prefix=prefix,
            definition_names=selected_names,
            gen_onefile=gen_onefile,
        )
        rendered_modules.append((definition_name, target, source_text))

    expected_header = [_GENERATED_HEADER, f"# Source: {declaration_file}"]
    for _, target, _ in rendered_modules:
        if target.exists():
            actual_header = target.read_text(encoding="utf-8").splitlines()[:2]
            if actual_header != expected_header:
                raise GenerationError(
                    f"refusing to overwrite non-generated file: {target}"
                )

    initialized_packages: set[Path] = set()
    for _, target, source_text in rendered_modules:
        target.parent.mkdir(parents=True, exist_ok=True)
        relative_parent = target.parent.relative_to(output_root)
        current = output_root
        for part in relative_parent.parts:
            current /= part
            if current in initialized_packages:
                continue
            init = current / "__init__.py"
            if not init.exists():
                init.write_text("", encoding="utf-8")
            initialized_packages.add(current)
        target.write_text(source_text, encoding="utf-8")

    if gen_onefile or schema.root_table is None:
        return rendered_modules[0][1]
    return next(
        target
        for definition_name, target, _ in rendered_modules
        if definition_name == schema.root_table
    )


__all__ = ["GenerationError", "generate", "render_module"]
