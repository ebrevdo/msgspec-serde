_GENERATED_HEADER = "# Generated by msgspec-serde. DO NOT EDIT."


class GenerationError(ValueError):
    """Report that a schema cannot be represented by the generator.

    Example:
        Catch generation errors separately from compiler errors:

        >>> try:
        ...     generate("unsupported.fbs", "generated")
        ... except GenerationError as error:
        ...     print(error)
    """


class _ScalarSpec(NamedTuple):
    python_type: str
    runtime_name: str
    numpy_type: str
    size: int


class _UnionArm(NamedTuple):
    tag: int
    object: ObjectDefinition


class _UnionPair(NamedTuple):
    value_field: FieldDefinition
    type_field: FieldDefinition
    enum: EnumDefinition
    arms: tuple[_UnionArm, ...]
    vector: bool


class _DynamicPair(NamedTuple):
    value_field: FieldDefinition
    type_field: FieldDefinition
    allowed_prefix: str


def _hidden_type_field_ids(
    union_pairs: Sequence[_UnionPair],
    dynamic_pairs: Sequence[_DynamicPair],
) -> set[int]:
    return {pair.type_field.id for pair in union_pairs} | {
        pair.type_field.id for pair in dynamic_pairs
    }


